//! Rust emission for the trial node tree, the counterpart of Twig's
//! Compiler and each Node's `compile()` method (`PrintNode`, `TextNode`, `IfNode`,
//! `ForNode`, `GetAttrExpression`, `FunctionExpression`, `FilterExpression`), and
//! of the escaper and safe-analysis node visitors: escaping is decided
//! here, at build time. Output is built with `quote` and laid out with
//! `prettyplease`.
//!
//! Upstream: twig/twig src/Compiler.php src/Node/PrintNode.php src/Node/TextNode.php src/Node/IfNode.php src/Node/ForNode.php src/Node/Expression/GetAttrExpression.php src/Node/Expression/FunctionExpression.php src/Node/Expression/FilterExpression.php src/NodeVisitor/EscaperNodeVisitor.php src/NodeVisitor/SafeAnalysisNodeVisitor.php

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::{
    Environment, Error, Number,
    parser::{Binary, CallType, Constant, Expr, Node, Unary},
};

struct Emitter<'a> {
    env: &'a Environment,
    template: &'a str,
    /// Names of all compiled templates, in emission order.
    names: Vec<String>,
}

pub fn emit(env: &Environment, templates: &[(String, Vec<Node>)]) -> Result<String, Error> {
    let names: Vec<String> = templates.iter().map(|(n, _)| n.clone()).collect();
    let mut functions = Vec::new();
    let mut lookup = Vec::new();
    for (index, (name, nodes)) in templates.iter().enumerate() {
        let emitter = Emitter {
            env,
            template: name,
            names: names.clone(),
        };
        let ident = format_ident!("render_{}", index);
        let body = emitter.nodes(nodes)?;
        let doc = format!(" `{name}`");
        functions.push(quote! {
            #[doc = #doc]
            pub fn #ident(env: &rt::Env, context: &mut rt::Context, out: &mut String) -> Result<(), rt::Error> {
                #[allow(dead_code)]
                const TEMPLATE: &str = #name;
                #body
                Ok(())
            }
        });
        lookup.push(quote! { #name => Some(#ident) });
    }
    let file = quote! {
        // Generated by twig-trial-compiler. Do not edit.
        use twig_trial_runtime as rt;

        #(#functions)*

        /// The compiled template registry (Environment::load()).
        pub fn template(name: &str) -> Option<rt::TemplateFn> {
            match name {
                #(#lookup,)*
                _ => None,
            }
        }
    };
    let parsed: syn::File = syn::parse2(file)
        .map_err(|e| Error::syntax(format!("Generated code does not parse: {e}"), "", 0))?;
    Ok(prettyplease::unparse(&parsed))
}

impl Emitter<'_> {
    fn err(&self, message: impl Into<String>, line: usize) -> Error {
        Error::syntax(message, self.template, line)
    }

    fn nodes(&self, nodes: &[Node]) -> Result<TokenStream, Error> {
        let mut out = TokenStream::new();
        for node in nodes {
            out.extend(self.node(node)?);
        }
        Ok(out)
    }

    fn node(&self, node: &Node) -> Result<TokenStream, Error> {
        Ok(match node {
            Node::Text(text) => {
                let mut chars = text.chars();
                if let (Some(c), None) = (chars.next(), chars.next()) {
                    quote! { out.push(#c); }
                } else {
                    quote! { out.push_str(#text); }
                }
            }
            Node::Print(expr, line) => {
                let value = self.expr(expr, *line)?;
                let line = *line as u32;
                if self.is_safe(expr) {
                    quote! { rt::write_raw(out, &#value).map_err(|e| e.at(TEMPLATE, #line))?; }
                } else {
                    quote! { rt::write_escaped_html(out, &#value).map_err(|e| e.at(TEMPLATE, #line))?; }
                }
            }
            Node::If { tests, otherwise } => {
                let mut chain = TokenStream::new();
                for (index, (condition, line, body)) in tests.iter().enumerate() {
                    let condition = self.expr(condition, *line)?;
                    let body = self.nodes(body)?;
                    if index > 0 {
                        chain.extend(quote! { else });
                    }
                    chain.extend(quote! { if rt::to_bool(&#condition) { #body } });
                }
                if let Some(otherwise) = otherwise {
                    let body = self.nodes(otherwise)?;
                    chain.extend(quote! { else { #body } });
                }
                chain
            }
            Node::For {
                key,
                value,
                sequence,
                line,
                body,
                otherwise,
            } => {
                // ForNode::compile(): `_parent` saves the context, the loop
                // variables are set per item, and afterwards they are unset
                // and the context is array_intersect_key($context, $_parent)
                // + $_parent.
                let sequence = self.expr(sequence, *line)?;
                let body = self.nodes(body)?;
                let set_key = key.as_ref().map(|k| quote! { rt::set(context, #k, key); });
                let key_binding = if key.is_some() {
                    quote! { key }
                } else {
                    quote! { _key }
                };
                let loop_variables: Vec<&str> = key
                    .iter()
                    .map(String::as_str)
                    .chain([value.as_str()])
                    .collect();
                let otherwise = if let Some(nodes) = otherwise {
                    let nodes = self.nodes(nodes)?;
                    quote! { if !iterated { #nodes } }
                } else {
                    quote! { let _ = iterated; }
                };
                quote! {
                    {
                        let parent = context.clone();
                        let items = rt::iterate(&#sequence);
                        let mut iterated = false;
                        for (#key_binding, item) in items {
                            #set_key
                            rt::set(context, #value, item);
                            #body
                            iterated = true;
                        }
                        #otherwise
                        rt::restore_after_loop(context, parent, &[#(#loop_variables),*]);
                    }
                }
            }
        })
    }

    /// `SafeAnalysisNodeVisitor`, for the `html` strategy.
    fn is_safe(&self, expr: &Expr) -> bool {
        match expr {
            Expr::Constant(_) => true,
            Expr::Ternary(_, then, otherwise) => self.is_safe(then) && self.is_safe(otherwise),
            Expr::Function { name, .. } => {
                name == "include" || self.env.function(name).is_some_and(|f| f.safe_html)
            }
            Expr::Filter { name, .. } => {
                name == "raw" || self.env.filter(name).is_some_and(|f| f.safe_html)
            }
            _ => false,
        }
    }

    fn exprs(&self, exprs: &[Expr], line: usize) -> Result<Vec<TokenStream>, Error> {
        exprs.iter().map(|e| self.expr(e, line)).collect()
    }

    fn expr(&self, expr: &Expr, line: usize) -> Result<TokenStream, Error> {
        Ok(match expr {
            Expr::Constant(c) => constant(c),
            Expr::Name(name) => quote! { rt::get(context, #name) },
            Expr::GetAttr {
                object,
                attribute,
                arguments,
                call,
            } => {
                let object = self.expr(object, line)?;
                let arguments = self.exprs(arguments, line)?;
                let call = match call {
                    CallType::Any => quote! { rt::CallType::Any },
                    CallType::Method => quote! { rt::CallType::Method },
                };
                let line = line as u32;
                quote! {
                    rt::get_attribute(env, &#object, #attribute, &[#(#arguments),*], #call)
                        .map_err(|e| e.at(TEMPLATE, #line))?
                }
            }
            Expr::Array(elements) => {
                let mut items = Vec::new();
                for (key, value) in elements {
                    let value = self.expr(value, line)?;
                    items.push(if let Some(key) = key {
                        let key = self.expr(key, line)?;
                        quote! { (Some(#key), #value) }
                    } else {
                        quote! { (None, #value) }
                    });
                }
                quote! { rt::array(vec![#(#items),*]) }
            }
            Expr::Unary(op, operand) => {
                let operand = self.expr(operand, line)?;
                match op {
                    Unary::Not => quote! { rt::Value::Bool(!rt::to_bool(&#operand)) },
                    Unary::Neg => quote! { rt::neg(&#operand) },
                    Unary::Pos => quote! { rt::pos(&#operand) },
                }
            }
            Expr::Binary(op, left, right) => {
                let l = self.expr(left, line)?;
                let r = self.expr(right, line)?;
                match op {
                    Binary::Or => quote! { rt::Value::Bool(rt::to_bool(&#l) || rt::to_bool(&#r)) },
                    Binary::And => quote! { rt::Value::Bool(rt::to_bool(&#l) && rt::to_bool(&#r)) },
                    Binary::Equal => quote! { rt::Value::Bool(rt::loose_eq(&#l, &#r)) },
                    Binary::NotEqual => quote! { rt::Value::Bool(!rt::loose_eq(&#l, &#r)) },
                    Binary::Less => quote! { rt::Value::Bool(rt::compare(&#l, &#r).is_lt()) },
                    Binary::Greater => quote! { rt::Value::Bool(rt::compare(&#l, &#r).is_gt()) },
                    Binary::LessEqual => quote! { rt::Value::Bool(rt::compare(&#l, &#r).is_le()) },
                    Binary::GreaterEqual => {
                        quote! { rt::Value::Bool(rt::compare(&#l, &#r).is_ge()) }
                    }
                    Binary::Add => quote! { rt::add(&#l, &#r) },
                    Binary::Sub => quote! { rt::sub(&#l, &#r) },
                    Binary::Mul => quote! { rt::mul(&#l, &#r) },
                    Binary::Concat => quote! { rt::concat(&#l, &#r) },
                    Binary::NullCoalesce => quote! { rt::null_coalesce(#l, || #r) },
                }
            }
            Expr::Ternary(condition, then, otherwise) => {
                let condition = self.expr(condition, line)?;
                let then = self.expr(then, line)?;
                let otherwise = self.expr(otherwise, line)?;
                quote! { if rt::to_bool(&#condition) { #then } else { #otherwise } }
            }
            Expr::Function {
                name,
                arguments,
                line,
            } => self.function(name, arguments, *line)?,
            Expr::Filter {
                node,
                name,
                arguments,
                line,
            } => {
                let line_number = *line;
                let node = self.expr(node, line_number)?;
                let arguments = self.exprs(arguments, line_number)?;
                let line = line_number as u32;
                if name == "raw" {
                    return Ok(node);
                }
                let Some(filter) = self.env.filter(name) else {
                    return Err(self.err(format!("Unknown \"{name}\" filter."), line_number));
                };
                let path: syn::Path = syn::parse_str(&filter.rust_path).map_err(|e| {
                    self.err(
                        format!("Invalid Rust path for filter \"{name}\": {e}"),
                        line_number,
                    )
                })?;
                quote! { #path(env, #node, &[#(#arguments),*]).map_err(|e| e.at(TEMPLATE, #line))? }
            }
        })
    }

    fn function(&self, name: &str, arguments: &[Expr], line: usize) -> Result<TokenStream, Error> {
        let line_number = line as u32;
        if name == "include" {
            // CoreExtension::include() with the default with_context=true.
            let [template, rest @ ..] = arguments else {
                return Err(self.err(
                    "Value for argument \"template\" is required for function \"include\".",
                    line,
                ));
            };
            if !rest.is_empty() {
                return Err(self.err(
                    "The Twig trial compiler supports include() with one argument only.",
                    line,
                ));
            }
            // A constant name that is compiled in the same set is called
            // directly; anything else goes through the registry.
            if let Expr::Constant(Constant::String(target)) = template
                && let Some(index) = self.names.iter().position(|n| n == target)
            {
                let ident = format_ident!("render_{}", index);
                return Ok(
                    quote! { rt::include_static(env, context, #ident).map_err(|e| e.at(TEMPLATE, #line_number))? },
                );
            }
            let template = self.expr(template, line)?;
            return Ok(
                quote! { rt::include(env, context, &#template).map_err(|e| e.at(TEMPLATE, #line_number))? },
            );
        }
        let Some(function) = self.env.function(name) else {
            return Err(self.err(format!("Unknown \"{name}\" function."), line));
        };
        let path: syn::Path = syn::parse_str(&function.rust_path).map_err(|e| {
            self.err(
                format!("Invalid Rust path for function \"{name}\": {e}"),
                line,
            )
        })?;
        let arguments = self.exprs(arguments, line)?;
        Ok(quote! { #path(env, &[#(#arguments),*]).map_err(|e| e.at(TEMPLATE, #line_number))? })
    }
}

fn constant(c: &Constant) -> TokenStream {
    match c {
        Constant::Null => quote! { rt::Value::Null },
        Constant::Bool(b) => quote! { rt::Value::Bool(#b) },
        Constant::Number(Number::Int(i)) => quote! { rt::Value::Int(#i) },
        Constant::Number(Number::Float(f)) => quote! { rt::Value::Float(#f) },
        Constant::String(s) => quote! { rt::Value::string(#s) },
    }
}
