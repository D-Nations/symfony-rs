<?php
// Runs the test methods of an upstream Symfony Yaml test class and
// records, as typed JSON (scripts/record.sh yaml), every call each test
// makes to the parser and the dumper, however it reaches them
// ($this->parser, `new Parser(...)`, Yaml::parse(), Yaml::dump(), ...):
// the constructor argument(s), the input, the other arguments, and what
// PHP returned or threw (a constructor that throws is recorded as a call
// too). With each test (and each data-provider row) go the exception the
// test expects and whether the test passed, so a recording is only kept
// when the upstream test passes on the oracle.
//
// The Parser and Dumper seen by the tests are subclasses of the real
// upstream classes (loaded from the pinned vendor copy under other names)
// that record their outermost calls; the nested parsers Parser creates
// for blocks are the real class and are not recorded.
//
//   php yaml_test_calls.php ParserTest

require '/demo/vendor/autoload.php';
require __DIR__ . '/lib/typed.php';

const TESTS = '/work/upstream/symfony/yaml/Tests';
/// Where YamlTestSuiteTest finds yaml/yaml-test-suite (scripts/fetch-upstream.sh).
const SUITE = '/work/upstream/symfony/yaml/vendor/yaml/yaml-test-suite';
/// Inputs and results longer than this are left out (only the input's
/// length is kept): a few tests generate megabytes with str_repeat().
const LARGE = 65536;

spl_autoload_register(static function (string $class): void {
    $name = match ($class) {
        'Symfony\Component\Yaml\Parser' => 'Parser',
        'Symfony\Component\Yaml\Dumper' => 'Dumper',
        default => null,
    };
    if (null === $name) {
        return;
    }
    $source = file_get_contents("/demo/vendor/symfony/yaml/$name.php");
    $source = str_replace("\nclass $name\n", "\nclass Recorded$name\n", $source, $count);
    if (1 !== $count || !str_starts_with($source, '<?php')) {
        throw new LogicException("unexpected $name.php layout");
    }
    eval(substr($source, 5));
    require __DIR__ . '/lib/recording_' . strtolower($name) . '.php';
}, true, true);

final class CallRecorder
{
    public static bool $active = false;
    public static array $calls = [];
    /// Temporary files the tests created, with the name they are recorded under.
    public static array $renames = [];
    private static int $depth = 0;

    /// Runs $call, recording $entry with what it returned or threw.
    /// $entry['input'] is the raw input; a string input over LARGE bytes
    /// keeps only its length.
    public static function record(array $entry, Closure $call): mixed
    {
        if (!self::$active || self::$depth > 0) {
            return $call();
        }
        ++self::$depth;
        if (\array_key_exists('input', $entry)) {
            // generated by str_repeat(); the Rust test builds it the same way
            $input = $entry['input'];
            $entry['input'] = typed_value(portable($input));
            if (\is_string($input) && \strlen($input) > LARGE) {
                $entry['input'] = ['omitted', \strlen($input)];
            } elseif (\strlen(json_encode($entry['input'])) > LARGE) {
                $entry['input'] = ['omitted'];
            }
        }
        try {
            $result = $call();
            $entry['result'] = typed_value(portable($result));
            if (\strlen(json_encode($entry['result'])) > LARGE) {
                $entry['result'] = ['omitted'];
            }

            return $result;
        } catch (Throwable $e) {
            $entry['result'] = ['throws', $e::class, portable($e->getMessage())];
            throw $e;
        } finally {
            self::$calls[] = $entry;
            --self::$depth;
        }
    }
}

/// The tests directory as "{tests}" and the YAML test suite as "{suite}"
/// in strings, so the Rust replay can put its own directories there; and
/// the temporary files the tests created under their stable names.
function portable(mixed $value): mixed
{
    $from = [...array_keys(CallRecorder::$renames), SUITE, TESTS];
    $to = [...array_values(CallRecorder::$renames), '{suite}', '{tests}'];

    return match (true) {
        \is_string($value) => str_replace($from, $to, $value),
        \is_array($value) => array_map('portable', $value),
        default => $value,
    };
}

foreach (glob(TESTS . '/Fixtures/*.php') as $fixture) {
    require_once $fixture;
}
$name = $argv[1] ?? 'ParserTest';
require_once TESTS . "/$name.php";
$class = "Symfony\\Component\\Yaml\\Tests\\$name";
$reflection = new ReflectionClass($class);

$expectation = static function (PHPUnit\Framework\TestCase $test): ?array {
    $read = static fn (string $property) => (new ReflectionProperty(PHPUnit\Framework\TestCase::class, $property))->getValue($test);
    if (null === $exception = $read('expectedException')) {
        return null;
    }

    return [
        'class' => $exception,
        'message' => $read('expectedExceptionMessage'),
        'matches' => $read('expectedExceptionMessageRegExp'),
    ];
};

$out = [];
$failures = [];
foreach ($reflection->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
    if (!str_starts_with($method->getName(), 'test')) {
        continue;
    }
    $rows = [[null, []]];
    foreach ($method->getAttributes(PHPUnit\Framework\Attributes\DataProvider::class) as $attribute) {
        $rows = [];
        foreach ($reflection->getMethod($attribute->getArguments()[0])->invoke(null) as $row => $arguments) {
            $rows[] = [(string) $row, array_values($arguments)];
        }
    }
    foreach ($rows as [$row, $arguments]) {
        $test = new $class($method->getName());
        $warnings = [];
        set_error_handler(static function (int $level, string $message) use (&$warnings): bool {
            $warnings[] = $message;

            return true;
        });
        CallRecorder::$calls = [];
        $thrown = null;
        $status = 'pass';
        try {
            (new ReflectionMethod($test, 'setUp'))->invoke($test);
            CallRecorder::$active = true;
            $method->invokeArgs($test, $arguments);
        } catch (PHPUnit\Framework\SkippedTest $e) {
            $status = 'skipped';
        } catch (Throwable $e) {
            $thrown = $e;
        } finally {
            CallRecorder::$active = false;
            (new ReflectionMethod($test, 'tearDown'))->invoke($test);
            restore_error_handler();
        }
        $expected = $expectation($test);
        if ('skipped' !== $status) {
            $ok = null === $expected
                ? null === $thrown
                : $thrown instanceof $expected['class']
                    && (null === $expected['message'] || str_contains($thrown->getMessage(), $expected['message']))
                    && (null === $expected['matches'] || preg_match($expected['matches'], $thrown->getMessage()));
            if (!$ok) {
                $status = 'fail';
                $failures[] = $method->getName() . (null === $row ? '' : " [$row]") . ': '
                    . (null === $thrown ? 'no exception' : $thrown::class . ': ' . $thrown->getMessage());
            }
        }
        if (null !== $expected) {
            $expected['message'] = null === $expected['message'] ? null : portable($expected['message']);
        }
        $out[$method->getName()][] = [
            'row' => $row,
            'status' => $status,
            'expected' => $expected,
            'calls' => CallRecorder::$calls,
        ];
    }
}
ksort($out);

if ($failures) {
    fwrite(STDERR, "upstream tests failing on the oracle:\n  " . implode("\n  ", $failures) . "\n");
    exit(1);
}

$lines = [];
foreach ($out as $test => $rows) {
    $lines[] = '  ' . json_encode($test) . ': ' . json_encode($rows, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
}
echo "{\n", implode(",\n", $lines), "\n}\n";
