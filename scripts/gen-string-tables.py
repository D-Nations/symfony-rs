#!/usr/bin/env python3
"""Generates crates/string/src/tables.rs, the data symfony/string's
wcswidth() reads, and crates/string/src/case_tables.rs:

- WIDE and ZERO from upstream/symfony/string/Resources/data/
  wcswidth_table_{wide,zero}.php (Symfony's own generated tables, MIT);
- EXTPICT from crates/string/tests/data/unicode.json, the code points the
  oracle's PCRE2 matches with \\p{ExtPict} (EMOJI_REGEX), recorded by
  scripts/record.sh string;
- case_tables.rs from crates/string/tests/data/case.tsv: mbstring's
  lower, upper, title, full and simple fold mappings, ICU's NFKC_CF, and
  the Cased / Case_Ignorable ranges of mb_strtolower()'s final sigma rule,
  per code point as the oracle answers (oracle/recorders/string_case.php).

    python scripts/gen-string-tables.py           rewrite the file
    python scripts/gen-string-tables.py --check   fail if it is stale

Standard library only.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "upstream" / "symfony" / "string" / "Resources" / "data"
VECTORS = ROOT / "crates" / "string" / "tests" / "data" / "unicode.json"
OUT = ROOT / "crates" / "string" / "src" / "tables.rs"
CASE = ROOT / "crates" / "string" / "tests" / "data" / "case.tsv"
CASE_OUT = ROOT / "crates" / "string" / "src" / "case_tables.rs"
COLUMNS = ["LOWER", "UPPER", "TITLE", "FOLD", "FOLD_SIMPLE", "NFKC_CF"]


def rust_str(text: str) -> str:
    out = []
    for ch in text:
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%X}" % ord(ch))
    return '"' + "".join(out) + '"'


def case_source() -> str:
    maps: dict[str, list[tuple[int, str]]] = {c: [] for c in COLUMNS}
    ranges: dict[str, list[tuple[int, int]]] = {"cased": [], "case_ignorable": []}
    versions = ""
    for line in CASE.read_text(encoding="utf-8").splitlines():
        if line.startswith("# PHP"):
            versions = line[2:]
            continue
        if line.startswith("#") or not line:
            continue
        cells = line.split("\t")
        if cells[0] in ranges:
            ranges[cells[0]].append((int(cells[1], 16), int(cells[2], 16)))
            continue
        cp = int(cells[0], 16)
        for name, value in zip(COLUMNS, cells[1:]):
            text = bytes.fromhex(value).decode("utf-8")
            if text != chr(cp):
                maps[name].append((cp, text))
    # NFKC_CF maps thousands of default ignorables to nothing: as ranges
    removed: list[tuple[int, int]] = []
    kept = []
    for cp, text in maps["NFKC_CF"]:
        if text == "":
            if removed and removed[-1][1] == cp - 1:
                removed[-1] = (removed[-1][0], cp)
            else:
                removed.append((cp, cp))
        else:
            kept.append((cp, text))
    maps["NFKC_CF"] = kept
    parts = [
        "//! Generated by scripts/gen-string-tables.py from tests/data/case.tsv; do\n"
        "//! not edit. Single code points as the oracle maps them\n"
        f"//! ({versions}):\n"
        "//! mbstring's `mb_strtolower()`, `mb_strtoupper()` and `mb_convert_case()`\n"
        "//! (title, fold, simple fold), ICU's `Normalizer::NFKC_CF`, and the Cased\n"
        "//! and Case_Ignorable ranges of `mb_strtolower()`'s final sigma rule. A\n"
        "//! code point missing from a table maps to itself.\n"
        "//!\n"
        "//! Upstream: none\n"
    ]
    for name in COLUMNS:
        rows = "\n".join(f"    (0x{cp:X}, {rust_str(text)})," for cp, text in maps[name])
        parts.append(f"\npub(crate) const {name}: &[(u32, &str)] = &[\n{rows}\n];\n")
    parts.append("\n/// Code points `Normalizer::NFKC_CF` removes.\n" + rust_table("NFKC_CF_REMOVED", removed))
    parts.append("\n" + rust_table("CASED", ranges["cased"]))
    parts.append("\n" + rust_table("CASE_IGNORABLE", ranges["case_ignorable"]))
    return "".join(parts)


def php_ranges(path: Path) -> tuple[str, list[tuple[int, int]]]:
    text = path.read_text(encoding="utf-8")
    version = re.search(r"Unicode version: (\S+)", text)
    numbers = [int(n) for n in re.findall(r"\b\d+\b", text.split("return", 1)[1])]
    if len(numbers) % 2:
        sys.exit(f"odd number of bounds in {path}")
    return (version.group(1) if version else "?"), list(zip(numbers[::2], numbers[1::2]))


def rust_table(name: str, ranges: list[tuple[int, int]]) -> str:
    rows = "\n".join(f"    (0x{a:X}, 0x{b:X})," for a, b in ranges)
    return f"pub(crate) const {name}: &[(u32, u32)] = &[\n{rows}\n];\n"


def main() -> int:
    version, wide = php_ranges(DATA / "wcswidth_table_wide.php")
    _, zero = php_ranges(DATA / "wcswidth_table_zero.php")
    vectors = json.loads(VECTORS.read_text(encoding="utf-8"))
    extpict = [tuple(r) for r in vectors["extpict"]]
    pcre = vectors["versions"]["pcre"]
    source = (
        "//! Generated by scripts/gen-string-tables.py; do not edit.\n"
        "//!\n"
        f"//! `WIDE` and `ZERO`: symfony/string's wcswidth tables (Unicode {version}),\n"
        "//! Symfony source copyright (c) Fabien Potencier; distributed under MIT.\n"
        f"//! `EXTPICT`: `\\p{{ExtPict}}` as the oracle's PCRE2 {pcre} matches it.\n"
        "//!\n"
        "//! Upstream: symfony/string Resources/data/wcswidth_table_wide.php Resources/data/wcswidth_table_zero.php\n\n"
        + rust_table("WIDE", wide) + "\n" + rust_table("ZERO", zero) + "\n" + rust_table("EXTPICT", extpict)
    )
    case = case_source()
    if "--check" in sys.argv[1:]:
        for out, text in ((OUT, source), (CASE_OUT, case)):
            if not out.is_file() or out.read_text(encoding="utf-8") != text:
                print(f"{out.relative_to(ROOT)} is stale; run scripts/gen-string-tables.py", file=sys.stderr)
                return 1
        return 0
    OUT.write_text(source, encoding="utf-8", newline="\n")
    CASE_OUT.write_text(case, encoding="utf-8", newline="\n")
    print(f"{CASE_OUT.relative_to(ROOT)} written")
    print(f"{OUT.relative_to(ROOT)}: {len(wide)} wide, {len(zero)} zero, {len(extpict)} ExtPict ranges")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
