#!/usr/bin/env python3
"""Generates crates/string/src/tables.rs, the data symfony/string's
wcswidth() reads:

- WIDE and ZERO from upstream/symfony/string/Resources/data/
  wcswidth_table_{wide,zero}.php (Symfony's own generated tables, MIT);
- EXTPICT from crates/string/tests/data/unicode.json, the code points the
  oracle's PCRE2 matches with \\p{ExtPict} (EMOJI_REGEX), recorded by
  scripts/record.sh string.

    python scripts/gen-string-tables.py           rewrite the file
    python scripts/gen-string-tables.py --check   fail if it is stale

Standard library only.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "upstream" / "symfony" / "string" / "Resources" / "data"
VECTORS = ROOT / "crates" / "string" / "tests" / "data" / "unicode.json"
OUT = ROOT / "crates" / "string" / "src" / "tables.rs"


def php_ranges(path: Path) -> tuple[str, list[tuple[int, int]]]:
    text = path.read_text(encoding="utf-8")
    version = re.search(r"Unicode version: (\S+)", text)
    numbers = [int(n) for n in re.findall(r"\b\d+\b", text.split("return", 1)[1])]
    if len(numbers) % 2:
        sys.exit(f"odd number of bounds in {path}")
    return (version.group(1) if version else "?"), list(zip(numbers[::2], numbers[1::2]))


def rust_table(name: str, ranges: list[tuple[int, int]]) -> str:
    rows = "\n".join(f"    (0x{a:X}, 0x{b:X})," for a, b in ranges)
    return f"pub(crate) const {name}: &[(u32, u32)] = &[\n{rows}\n];\n"


def main() -> int:
    version, wide = php_ranges(DATA / "wcswidth_table_wide.php")
    _, zero = php_ranges(DATA / "wcswidth_table_zero.php")
    vectors = json.loads(VECTORS.read_text(encoding="utf-8"))
    extpict = [tuple(r) for r in vectors["extpict"]]
    pcre = vectors["versions"]["pcre"]
    source = (
        "//! Generated by scripts/gen-string-tables.py; do not edit.\n"
        "//!\n"
        f"//! `WIDE` and `ZERO`: symfony/string's wcswidth tables (Unicode {version}),\n"
        "//! Symfony source copyright (c) Fabien Potencier; distributed under MIT.\n"
        f"//! `EXTPICT`: `\\p{{ExtPict}}` as the oracle's PCRE2 {pcre} matches it.\n"
        "//!\n"
        "//! Upstream: symfony/string Resources/data/wcswidth_table_wide.php Resources/data/wcswidth_table_zero.php\n\n"
        + rust_table("WIDE", wide) + "\n" + rust_table("ZERO", zero) + "\n" + rust_table("EXTPICT", extpict)
    )
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != source:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/gen-string-tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(wide)} wide, {len(zero)} zero, {len(extpict)} ExtPict ranges")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
