#!/usr/bin/env python3
"""Generates crates/mime/src/map.rs, the MAP and REVERSE_MAP constants of
upstream/symfony/mime/MimeTypes.php (Symfony's own generated tables, MIT),
in upstream's order.

    python scripts/gen-mime-types.py           rewrite the file
    python scripts/gen-mime-types.py --check   fail if it is stale

Standard library only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "upstream" / "symfony" / "mime" / "MimeTypes.php"
OUT = ROOT / "crates" / "mime" / "src" / "map.rs"

ROW = re.compile(r"^\s*'([^'\\]*)' => \[((?:'[^'\\]*'(?:, )?)*)\],$")
ITEM = re.compile(r"'([^'\\]*)'")


def table(lines: list[str], name: str) -> list[tuple[str, list[str]]]:
    start = lines.index(f"    private const {name} = [")
    rows: list[tuple[str, list[str]]] = []
    seen: set[str] = set()
    for line in lines[start + 1 :]:
        if line == "    ];":
            return rows
        m = ROW.match(line)
        if not m:
            sys.exit(f"{SOURCE}: unexpected line in {name}: {line!r}")
        key = m.group(1)
        if key in seen:
            sys.exit(f"{SOURCE}: duplicate key {key!r} in {name}")
        seen.add(key)
        rows.append((key, ITEM.findall(m.group(2))))
    sys.exit(f"{SOURCE}: {name} is not closed")


def rust(name: str, rows: list[tuple[str, list[str]]]) -> str:
    out = ["#[rustfmt::skip]", f"pub(crate) const {name}: &[(&str, &[&str])] = &["]
    for key, values in rows:
        items = ", ".join(f'"{v}"' for v in values)
        out.append(f'    ("{key}", &[{items}]),')
    out.append("];")
    return "\n".join(out)


def main() -> None:
    lines = SOURCE.read_text(encoding="utf-8").splitlines()
    for line in lines:
        if '"' in line and "=>" in line:
            sys.exit(f"{SOURCE}: a double quote in a row: {line!r}")
    text = "\n".join(
        [
            "//! Generated by scripts/gen-mime-types.py from MimeTypes.php's MAP and",
            "//! REVERSE_MAP constants (in upstream's order); do not edit.",
            "//!",
            "//! Symfony source copyright (c) Fabien Potencier; distributed under MIT.",
            "//!",
            "//! Upstream: symfony/mime MimeTypes.php",
            "",
            "/// `MimeTypes::MAP`: MIME types and their extensions.",
            rust("MAP", table(lines, "MAP")),
            "",
            "/// `MimeTypes::REVERSE_MAP`: extensions and their MIME types.",
            rust("REVERSE_MAP", table(lines, "REVERSE_MAP")),
            "",
        ]
    )
    if sys.argv[1:] == ["--check"]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT} is stale: run python scripts/gen-mime-types.py")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
